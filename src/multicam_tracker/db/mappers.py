def _to_uuid(value: str, *, field_name: str) -> uuid.UUID:
    """Parse a domain identifier string into a UUID for the database.

    Args:
        value: The identifier as carried by the domain model.
        field_name: Field name reported in the error context.

    Returns:
        The parsed UUID.

    Raises:
        StorageError: If the value is not a well-formed UUID. Raised here rather
            than at the driver so the offending field is named.
    """
    try:
        return uuid.UUID(value)
    except (ValueError, AttributeError, TypeError) as exc:
        raise StorageError(
            "Identifier is not a valid UUID",
            {"field": field_name, "value": str(value)},
        ) from exc


