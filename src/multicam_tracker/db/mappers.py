def camera_to_orm(camera: Camera) -> CameraORM:
    """Convert a :class:`Camera` to its row representation.

    Args:
        camera: The domain model.

    Returns:
        An unattached ORM instance.
    """
    return CameraORM(
        camera_id=camera.camera_id,
        name=camera.name,
        lat=camera.lat,
        lon=camera.lon,
        heading_degrees=camera.heading_degrees,
        clock_offset_ms=camera.clock_offset_ms,
        enabled=camera.enabled,
        notes=camera.notes,
    )


def camera_to_domain(row: CameraORM) -> Camera:
    """Convert a camera row to its domain model.

    Args:
        row: The ORM instance.

    Returns:
        The validated domain model.
    """
    return Camera(
        camera_id=row.camera_id,
        name=row.name,
        lat=row.lat,
        lon=row.lon,
        heading_degrees=row.heading_degrees,
        clock_offset_ms=row.clock_offset_ms,
        enabled=row.enabled,
        notes=row.notes,
    )


