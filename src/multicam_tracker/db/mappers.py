# Field-set correspondence
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class FieldCorrespondence:
    """Declares how one domain model's fields line up with one table's columns.

    Args:
        domain_model: The Pydantic model.
        orm_model: The SQLAlchemy model.
        renamed: Domain field name -> column name, where the two differ.
        domain_only: Domain field -> why it has no column of its own.
        orm_only: Column -> why it has no domain field.
    """

    domain_model: type[MCTBaseModel]
    orm_model: type[Base]
    renamed: dict[str, str] = field(default_factory=dict)
    domain_only: dict[str, str] = field(default_factory=dict)
    orm_only: dict[str, str] = field(default_factory=dict)

    def unmapped_domain_fields(self) -> set[str]:
        """Return domain fields with neither a matching column nor a justification.

        Returns:
            Field names that would be silently dropped on the way to the
            database. Any non-empty result is a bug.
        """
        columns = orm_column_names(self.orm_model)
        return {
            name
            for name in self.domain_model.model_fields
            if name not in self.domain_only and self.renamed.get(name, name) not in columns
        }

    def unmapped_orm_columns(self) -> set[str]:
        """Return columns with neither a matching domain field nor a justification.

        Returns:
            Column names that would never be populated from a domain model.
        """
        populated = {
            self.renamed.get(name, name)
            for name in self.domain_model.model_fields
            if name not in self.domain_only
        }
        return orm_column_names(self.orm_model) - populated - set(self.orm_only)


FIELD_CORRESPONDENCE: tuple[FieldCorrespondence, ...] = (
    FieldCorrespondence(Camera, CameraORM),
    FieldCorrespondence(CameraLink, CameraLinkORM),
    FieldCorrespondence(
        Sighting,
        SightingORM,
        orm_only={
            "plate_folded": (
                "Generated column maintained by Postgres from plate_text_normalized. "
                "It exists to index fuzzy lookups and is never written or read by "
                "the domain layer."
            )
        },
    ),
    FieldCorrespondence(Target, TargetORM),
    FieldCorrespondence(MatchCandidate, MatchCandidateORM),
    FieldCorrespondence(
        Trajectory,
        TrajectoryORM,
        renamed={"sightings": "sighting_ids"},
        domain_only={
            "hops": (
                "Stored in the trajectory_hops table with an explicit position "
                "column, so hop order survives a query without an ORDER BY."
            )
        },
    ),
    FieldCorrespondence(
        TrajectoryHop,
        TrajectoryHopORM,
        orm_only={
            "trajectory_id": "Parent key; the domain model is nested inside its Trajectory.",
            "position": "Explicit ordering, since SQL result order is not guaranteed.",
        },
    ),
)
"""Every domain-model/table pair, with each mismatch justified in writing.

A field added to a domain model but not to its table produces an entry in
:meth:`FieldCorrespondence.unmapped_domain_fields`, which a unit test asserts is
empty. That is the mechanism that makes "mapping must be total" enforceable
rather than a promise.
"""


def correspondence_for(domain_model: type[MCTBaseModel]) -> FieldCorrespondence:
    """Return the correspondence entry for ``domain_model``.

    Args:
        domain_model: The Pydantic model to look up.

    Returns:
        Its correspondence declaration.

    Raises:
        StorageError: If the model has no declared correspondence, which means a
            new entity was added without a mapping.
    """
    for entry in FIELD_CORRESPONDENCE:
        if entry.domain_model is domain_model:
            return entry
    raise StorageError(
        "No field correspondence declared for this domain model",
        {"model": domain_model.__name__},
    )


def orm_column_names(orm_model: type[Base]) -> set[str]:
    """Return the column names of an ORM model.

    Args:
        orm_model: The SQLAlchemy model.

    Returns:
        Its column keys.
    """
    return {column.key for column in orm_model.__table__.columns}


def domain_field_names(domain_model: type[MCTBaseModel]) -> set[str]:
    """Return the field names of a domain model.

    Args:
        domain_model: The Pydantic model.

    Returns:
        Its declared field names.
    """
    return set(domain_model.model_fields)
