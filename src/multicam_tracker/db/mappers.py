def trajectory_to_orm(trajectory: Trajectory) -> tuple[TrajectoryORM, list[TrajectoryHopORM]]:
    """Convert a :class:`Trajectory` to its row and its hop rows.

    Hops carry an explicit ``position`` because SQL result order is not
    guaranteed without an ORDER BY, and a trajectory whose hops came back
    shuffled would describe a different route.

    Args:
        trajectory: The domain model.

    Returns:
        The trajectory row and its ordered hop rows.
    """
    trajectory_uuid = _to_uuid(trajectory.trajectory_id, field_name="trajectory_id")

    row = TrajectoryORM(
        trajectory_id=trajectory_uuid,
        target_id=_to_uuid(trajectory.target_id, field_name="target_id"),
        sighting_ids=[
            _to_uuid(sighting.sighting_id, field_name="sightings[].sighting_id")
            for sighting in trajectory.sightings
        ],
        overall_confidence=trajectory.overall_confidence,
        start_time_utc=trajectory.start_time_utc,
        end_time_utc=trajectory.end_time_utc,
        gaps=[gap.to_json_dict() for gap in trajectory.gaps],
        temporal_integrity=(
            trajectory.temporal_integrity.to_json_dict()
            if trajectory.temporal_integrity is not None
            else None
        ),
        requires_recomputation=trajectory.requires_recomputation,
    )

    hops = [
        TrajectoryHopORM(
            trajectory_id=trajectory_uuid,
            position=position,
            from_sighting_id=_to_uuid(hop.from_sighting_id, field_name="hops[].from_sighting_id"),
            to_sighting_id=_to_uuid(hop.to_sighting_id, field_name="hops[].to_sighting_id"),
            from_camera_id=hop.from_camera_id,
            to_camera_id=hop.to_camera_id,
            elapsed_sec=hop.elapsed_sec,
            topology_plausible=hop.topology_plausible,
            hop_confidence=hop.hop_confidence,
        )
        for position, hop in enumerate(trajectory.hops)
    ]

    return row, hops


def trajectory_to_domain(
    row: TrajectoryORM,
    hop_rows: list[TrajectoryHopORM],
    sightings: list[Sighting],
) -> Trajectory:
    """Rebuild a :class:`Trajectory` from its rows and its resolved sightings.

    Sightings are passed in rather than loaded here so the mapper stays free of
    database access; the repository resolves them in ``sighting_ids`` order.

    Args:
        row: The trajectory row.
        hop_rows: Its hop rows, which are sorted by ``position`` here regardless
            of the order they arrive in.
        sightings: The trajectory's sightings, in chronological order.

    Returns:
        The validated domain model.
    """
    ordered_hops = sorted(hop_rows, key=lambda hop: hop.position)

    return Trajectory(
        trajectory_id=str(row.trajectory_id),
        target_id=str(row.target_id),
        sightings=sightings,
        hops=[
            TrajectoryHop(
                from_sighting_id=str(hop.from_sighting_id),
                to_sighting_id=str(hop.to_sighting_id),
                from_camera_id=hop.from_camera_id,
                to_camera_id=hop.to_camera_id,
                elapsed_sec=hop.elapsed_sec,
                topology_plausible=hop.topology_plausible,
                hop_confidence=hop.hop_confidence,
            )
            for hop in ordered_hops
        ],
        overall_confidence=row.overall_confidence,
        start_time_utc=row.start_time_utc,
        end_time_utc=row.end_time_utc,
        gaps=[CoverageGap.from_json_dict(gap) for gap in row.gaps],
        temporal_integrity=(
            TemporalIntegrity.from_json_dict(row.temporal_integrity)
            if row.temporal_integrity is not None
            else None
        ),
        requires_recomputation=row.requires_recomputation,
    )


