"""Explicit conversion between Pydantic domain models and SQLAlchemy rows.

Every mapping is written out by hand rather than generated by attribute copying.
Reflection would appear to work and would silently drop any field whose name
differs between the two layers -- exactly the failure this module exists to
prevent. The cost is that adding a field means editing here too, which is why
:data:`FIELD_CORRESPONDENCE` exists and is asserted by a test: forget the edit
and the suite fails naming the field.
"""

