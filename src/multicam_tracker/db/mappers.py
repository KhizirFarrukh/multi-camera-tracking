def sighting_to_orm(sighting: Sighting) -> SightingORM:
    """Convert a :class:`Sighting` to its row representation.

    ``plate_folded`` is deliberately not set: it is a generated column that
    Postgres maintains from ``plate_text_normalized``.

    Args:
        sighting: The domain model.

    Returns:
        An unattached ORM instance.
    """
    return SightingORM(
        sighting_id=_to_uuid(sighting.sighting_id, field_name="sighting_id"),
        camera_id=sighting.camera_id,
        timestamp_utc=sighting.timestamp_utc,
        raw_timestamp=sighting.raw_timestamp,
        clock_offset_applied_ms=sighting.clock_offset_applied_ms,
        object_class=sighting.object_class.value,
        detection_confidence=sighting.detection_confidence,
        bbox=list(sighting.bbox),
        frame_index=sighting.frame_index,
        plate_text_raw=sighting.plate_text_raw,
        plate_text_normalized=sighting.plate_text_normalized,
        plate_confidence=sighting.plate_confidence,
        embedding=list(sighting.embedding) if sighting.embedding is not None else None,
        embedding_model_version=sighting.embedding_model_version,
        thumbnail_path=sighting.thumbnail_path,
        source_id=sighting.source_id,
        created_at=sighting.created_at,
    )


def sighting_to_domain(row: SightingORM) -> Sighting:
    """Convert a sighting row to its domain model.

    Args:
        row: The ORM instance.

    Returns:
        The validated domain model.

    Raises:
        pydantic.ValidationError: If the stored row violates a domain invariant,
            which would mean the row was written by something that bypassed this
            layer.
    """
    return Sighting(
        sighting_id=str(row.sighting_id),
        camera_id=row.camera_id,
        timestamp_utc=row.timestamp_utc,
        raw_timestamp=row.raw_timestamp,
        clock_offset_applied_ms=row.clock_offset_applied_ms,
        object_class=ObjectClass(row.object_class),
        detection_confidence=row.detection_confidence,
        bbox=list(row.bbox),
        frame_index=row.frame_index,
        plate_text_raw=row.plate_text_raw,
        plate_text_normalized=row.plate_text_normalized,
        plate_confidence=row.plate_confidence,
        embedding=[float(component) for component in row.embedding]
        if row.embedding is not None
        else None,
        embedding_model_version=row.embedding_model_version,
        thumbnail_path=row.thumbnail_path,
        source_id=row.source_id,
        created_at=row.created_at,
    )


