@requires_opencv
def test_the_decoder__is_released_when_iteration_finishes() -> None:
    """A finished file has nothing more to give, and holding its handle is how a
    batch run exhausts its descriptors."""
    source = _source(CLEAN)
    source.open()

    list(source.frames())

    assert not source.is_open


@requires_opencv
def test_opening_many_files_in_sequence__leaves_none_open() -> None:
    """The batch case, against real decoder handles rather than counters."""
    sources = []
    for _ in range(50):
        source = _source(CLEAN, max_frames=1)
        with source:
            list(source.frames())
        sources.append(source)

    assert not any(source.is_open for source in sources)
