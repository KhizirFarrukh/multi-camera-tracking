@requires_pyav
def test_a_variable_rate_file__gets_its_timestamps_from_presentation_times() -> None:
    """The nominal rate is a lie in this file, and following it puts every frame
    after the first gap at the wrong instant.

    The offsets are the ones the fixture was authored with -- uneven on purpose.
    """
    with _source(VFR, prefer_pyav=True) as source:
        offsets = [
            round((frame.timestamp_utc - START).total_seconds(), 3) for frame in source.frames()
        ]

    assert offsets == [0.0, 0.1, 0.2, 0.3, 0.7, 0.8, 1.5, 1.6, 1.7, 3.0]


@requires_pyav
def test_the_nominal_rate_of_a_variable_rate_file__disagrees_with_its_timestamps() -> None:
    """Documents *why* the presentation times are used.

    If the nominal rate were right, the naive arithmetic would work and this
    module would be simpler than it is.
    """
    with _source(VFR, prefer_pyav=True) as source:
        nominal = source.properties.fps
        frames = list(source.frames())

    naive_last = float(Fraction(len(frames) - 1) / nominal)
    actual_last = (frames[-1].timestamp_utc - START).total_seconds()

    assert abs(naive_last - actual_last) > 0.2


@requires_pyav
def test_the_pyav_backend__reports_the_real_codec_name() -> None:
    """OpenCV cannot say what it decoded; PyAV can, and errors need it."""
    with _source(CLEAN, prefer_pyav=True) as source:
        assert source.backend == DecoderBackend.PYAV
        assert source.properties.codec not in {None, "", DecoderBackend.OPENCV}


@requires_pyav
def test_both_backends__agree_on_the_frame_count_of_a_clean_file() -> None:
    """Two decoders, one answer. A disagreement here would make every count
    dependent on which library happened to be installed."""
    with _source(CLEAN) as opencv_source:
        opencv_frames = len(list(opencv_source.frames()))
    with _source(CLEAN, prefer_pyav=True) as pyav_source:
        pyav_frames = len(list(pyav_source.frames()))

    assert opencv_frames == pyav_frames == EXPECTED_FRAMES


